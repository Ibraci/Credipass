import assert from 'node:assert/strict';
import * as L from '../src/modules/creditLedgerR15.js';
const db=L.seed();
assert.equal(db.version,17);
const sal=db.applications.find(a=>a.product==='Crédit salarié'); const pme=db.applications.find(a=>a.product==='Crédit PME');
assert.ok(sal&&pme,'Deux parcours produit');
assert.deepEqual(L.productDefinition('Crédit salarié').workflow,['AGENT_CREDIT','ANALYSTE_RESPONSABLE_CREDIT','COMITE_CREDIT']);
assert.deepEqual(L.productDefinition('Crédit PME').workflow,['AGENT_CREDIT','ANALYSTE_RESPONSABLE_CREDIT','COMITE_CREDIT']);
L.saveProductForm(db,sal.id,{netSalary:400000,assignableQuota:150000,monthlyRepayment:120000,employer:'Employeur test',salaryDomiciliationDate:'2025-01-01'},'Test');
assert.equal(L.salaryCapacity(db,sal.id).compliant,true); assert.equal(L.salaryCapacity(db,sal.id).margin,30000);
L.saveBusinessAnalysis(db,{applicationId:pme.id,sales:1000000,purchases:550000,operatingExpenses:150000,market:'Local',competitors:'3',customers:'Détaillants',pricesVolumes:'Documentés'},'Test');
const d=L.dossier(db,pme.id); assert.equal(d.businessAnalysis.grossMargin,450000); assert.equal(d.businessAnalysis.result,300000);
L.savePersonalBudget(db,{applicationId:pme.id,salary:0,otherIncome:200000,personalExpenses:100000,creditTontinePayments:30000},'Test');
L.savePersonalBalance(db,{applicationId:pme.id,savings:200000,cash:100000,furniture:300000,vehicle:500000,property:2000000,bankDebt:300000,otherCreditors:100000},'Test');
assert.equal(L.dossier(db,pme.id).personalBudget.net,70000); assert.equal(L.dossier(db,pme.id).personalBalance.netWorth,2700000);
for(const item of L.policySummary(db,pme.id).items)L.setPolicyCheck(db,pme.id,item.code,'Conforme','Preuve test','Test');
assert.equal(L.policySummary(db,pme.id).compliant,true);
for(const dim of L.RISK_DIMENSIONS)L.setInstitutionalRisk(db,pme.id,dim,'Satisfaisant','Preuve test','Test');
assert.equal(L.dossier(db,pme.id).institutionalRisk.length,9);
for(const step of L.productDefinition('Crédit PME').workflow)L.recordWorkflowAction(db,pme.id,step,'VALIDÉ','Test','Test');
assert.equal(L.workflowState(db,pme.id).next,'TERMINÉ');
assert.ok(L.checklist(db,sal.id).items.some(x=>x.label==='Justificatif de salaire'));
assert.ok(L.checklist(db,pme.id).items.some(x=>x.label==='Documents légaux applicables'));
console.log('R15 INSTITUTIONAL CREDIT PROCESS: PASS');
