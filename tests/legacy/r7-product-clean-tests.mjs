import fs from 'node:fs';
import path from 'node:path';
const root=process.cwd();
const app=fs.readFileSync(path.join(root,'src/app.js'),'utf8');
const sw=fs.readFileSync(path.join(root,'sw.js'),'utf8');
const checks=[];
const ok=(name,v)=>{if(!v)throw new Error(`FAIL ${name}`); checks.push(name);};
ok('scenario actions normalized', !app.includes('data-cp-action="demo-'));
ok('jury naming removed from product UI', !app.toLowerCase().includes('jury'));
ok('obsolete service-worker paths removed', !/demo-aissata|demoScenarioEngine|institutional-pilot\.js|portfolio-demo\.js/.test(sw));
const refs=[...sw.matchAll(/'\.\/(.*?)'/g)].map(m=>m[1]).filter(x=>x && x!=='.');
const missing=refs.filter(x=>!fs.existsSync(path.join(root,x)));
ok('all service-worker precache assets exist', missing.length===0);
ok('R7 cache namespace', sw.includes("credipass-r7-product-clean"));
ok('human decision retained', /L'humain décide|L’humain décide/.test(app));
ok('character trust retained', /Caractère|Character/.test(app));
ok('portfolio retained', /Portefeuille à risque/.test(app));
console.log(`R7_PRODUCT_CLEAN_PASS ${checks.length}/8`);
for(const x of checks) console.log(`[PASS] ${x}`);
