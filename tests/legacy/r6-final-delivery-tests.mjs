import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
const root=process.cwd();
const checks=[];
const ok=(name,cond)=>{ if(!cond) throw new Error(`FAIL ${name}`); checks.push(name); };
const pkg=JSON.parse(fs.readFileSync(path.join(root,'package.json'),'utf8'));
ok('package identity',pkg.name==='credipass' && pkg.version==='6.0.0');
ok('UI script target exists',pkg.scripts['test:ui']==='node tests/closure-ui-tests.mjs' && fs.existsSync(path.join(root,'tests/closure-ui-tests.mjs')));
const app=fs.readFileSync(path.join(root,'src/app.js'),'utf8');
const html=fs.readFileSync(path.join(root,'index.html'),'utf8');
ok('no obsolete CIF demo tenant',!app.includes('CIF-DEMO-ML') && !html.includes('CIF-DEMO-ML'));
ok('no fake PAR constants',!app.includes('0.72') && !app.includes('0.08'));
ok('human decision retained',app.includes('humanDecision'));
ok('character trust present',app.includes('trustVerification'));
ok('portfolio present',app.includes('portfolioRisk'));
execFileSync(process.execPath,['tests/closure-ui-tests.mjs'],{cwd:root,stdio:'pipe'});
checks.push('closure UI executable');
console.log(`R6 FINAL DELIVERY PASS ${checks.length}/${checks.length}`);
for(const c of checks) console.log(`[PASS] ${c}`);
