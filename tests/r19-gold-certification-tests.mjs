import assert from 'node:assert/strict';
import fs from 'node:fs';
import * as L from '../src/modules/creditLedgerR15.js';
import {ROLES,DEMO_USERS} from '../src/modules/accessControlR18.js';
import {ensureCatalog,activeProducts} from '../src/modules/productCatalogR186.js';
const read=p=>fs.readFileSync(new URL('../'+p,import.meta.url),'utf8');
const db=ensureCatalog(L.seed());
assert.equal(Object.keys(ROLES).length,10,'10 rôles de référence');
assert.equal(DEMO_USERS.length,10,'10 comptes de référence');
assert.ok(db.members.length>=25 && db.applications.length>=25,'25 membres/dossiers minimum');
assert.ok(activeProducts(db).length>=9,'9 familles/produits actifs minimum');
const agent=DEMO_USERS.find(x=>x.login==='agent.credit');
const gerant=DEMO_USERS.find(x=>x.login==='gerant');
assert.ok(agent && gerant); assert.ok(!ROLES[agent.role].permissions.includes('MEMBER_CREATE')); assert.ok(ROLES[gerant.role].permissions.includes('MEMBER_CREATE'));
const html=read('index.html'), ui=read('src/az-app.js'), css=read('src/az.css'), sw=read('sw.js');
assert.ok(html.includes('assets/logo-credipass.png'),'logo officiel');
assert.match(html,/az-app\.js\?r=19\.[0-9]+/,'cache-busting lignée R19');
assert.ok(!html.includes('Institution • Démonstration'),'pas de mode démo visible');
assert.ok(sw.includes('credipass-r19'),'cache lignée R19');
for(const t of ['Hors connexion','Passeport financier','Importer un fichier Excel','Résultat BIC','Traçabilité complète du dossier','Produits de crédit actifs']) assert.ok(ui.includes(t),t);
for(const t of ['@media(max-width:620px)','@media print','focus-visible','.fieldbar.offline']) assert.ok(css.includes(t),t);
for(const bad of ['Démo Jury','Mode jury','Pitch jury']) assert.ok(!ui.includes(bad) && !html.includes(bad),`élément externe absent: ${bad}`);
console.log(`R19 GOLD CERTIFICATION: PASS — ${Object.keys(ROLES).length} rôles, ${db.members.length} membres, ${db.applications.length} dossiers, ${activeProducts(db).length} produits actifs`);
